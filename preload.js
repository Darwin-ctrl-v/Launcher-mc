const { contextBridge, ipcRenderer } = require("electron");
const on = (channel, cb) => ipcRenderer.on(channel, (_e, data) => cb(data));

contextBridge.exposeInMainWorld("api", {
  getBranding: () => ipcRenderer.invoke("branding"),
  getSession: () => ipcRenderer.invoke("session:get"),
  login: () => ipcRenderer.invoke("login"),
  logout: () => ipcRenderer.invoke("logout"),
  play: (instanceId) => ipcRenderer.invoke("play", instanceId),
  getProfile: () => ipcRenderer.invoke("profile:get"),
  pickSkin: () => ipcRenderer.invoke("skin:pick"),
  uploadSkin: (variant) => ipcRenderer.invoke("skin:upload", variant),
  setCape: (id) => ipcRenderer.invoke("cape:set", id),
  listInstances: () => ipcRenderer.invoke("instances:list"),
  selectInstance: (id) => ipcRenderer.invoke("instances:select", id),
  instanceImage: (id) => ipcRenderer.invoke("instances:image", id),
  createInstance: (data) => ipcRenderer.invoke("instances:create", data),
  deleteInstance: (id) => ipcRenderer.invoke("instances:delete", id),
  openInstanceFolder: (id, subfolder) => ipcRenderer.invoke("instances:openFolder", id, subfolder),
  listMods: (instanceId) => ipcRenderer.invoke("mods:list", instanceId),
  addModFiles: (instanceId) => ipcRenderer.invoke("mods:addFiles", instanceId),
  deleteModFile: (instanceId, filename) => ipcRenderer.invoke("mods:deleteFile", instanceId, filename),
  getSettings: () => ipcRenderer.invoke("settings:get"),
  setRam: (mb) => ipcRenderer.invoke("settings:setRam", mb),
  setSettings: (data) => ipcRenderer.invoke("settings:set", data),
  installUpdate: () => ipcRenderer.invoke("update:install"),
  onStatus: (cb) => on("status", cb),
  onLog: (cb) => on("log", cb),
  onProgress: (cb) => on("progress", cb),
  onState: (cb) => on("state", cb),
  onUpdate: (cb) => on("update", cb),
});
